// Embeds db/migrations/*.sql into src/lib/migrations.generated.ts so the deployed
// app can apply pending migrations itself. Run after adding a migration:
//   node scripts/gen-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../db/migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(new URL(f, dir), "utf8"))} },`);
writeFileSync(
  new URL("../src/lib/migrations.generated.ts", import.meta.url),
  `// Generated by scripts/gen-migrations.mjs from db/migrations — do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`embedded ${files.length} migrations`);
